def boshlash(talaba_id):
    """Talaba ID raqamini qabul qilib, uning variantidagi ma'lumotlarni qaytaradi."""
    if talaba_id in (None, 0, '', '0'):
        raise ValueError("TALABA_ID ni o'zingizning talaba raqamingiz bilan almashtiring!")
    v = int(str(talaba_id).strip()) % VARIANTLAR_SONI
    _HOLAT.update(id=str(talaba_id).strip(), v=v, natija={})
    print(f"Talaba ID: {_HOLAT['id']}  |  Variant: {v + 1}")
    print(f"Topshiriqlar soni: {len(TOPSHIRIQLAR)}  |  Maksimal ball: {sum(t[0] for t in TOPSHIRIQLAR.values())}")
    return _malumot(v)


def tekshir(kalit, javob):
    """Topshiriq javobini tekshiradi va natijani yozib qo'yadi."""
    if _HOLAT['v'] is None:
        print("Avval boshlash(TALABA_ID) ni ishga tushiring.")
        return False
    ball, tur, izoh = TOPSHIRIQLAR[kalit]
    if javob is Ellipsis or javob is None:
        print(f"⏳ {kalit}: javob hali yozilmagan.")
        _HOLAT['natija'][kalit] = 0
        return False
    try:
        matn = _norm(tur, javob)
    except Exception:
        print(f"❌ {kalit}: javob turi noto'g'ri. Kutilgan: {izoh}")
        _HOLAT['natija'][kalit] = 0
        return False
    if _xesh(kalit, _HOLAT['v'], matn) == _XESHLAR[str(_HOLAT['v'])][kalit]:
        print(f"✅ {kalit}: to'g'ri! (+{ball} ball)")
        _HOLAT['natija'][kalit] = ball
        return True
    print(f"❌ {kalit}: noto'g'ri. Kutilgan javob turi: {izoh}. Kodingizni qayta ko'rib chiqing.")
    _HOLAT['natija'][kalit] = 0
    return False


def natija(saqlash=True):
    """Umumiy natijani chiqaradi va natija_<ID>.json fayliga yozadi."""
    jami = sum(_HOLAT['natija'].values())
    maks = sum(t[0] for t in TOPSHIRIQLAR.values())
    print(f"Talaba ID: {_HOLAT['id']}  |  Variant: {(_HOLAT['v'] or 0) + 1}")
    for k in TOPSHIRIQLAR:
        b = _HOLAT['natija'].get(k)
        belgi = '✅' if b else ('❌' if b == 0 else '⏳')
        print(f"  {belgi} {k:5s}  {b or 0}/{TOPSHIRIQLAR[k][0]}")
    print(f"JAMI: {jami} / {maks}")
    if saqlash and _HOLAT['id']:
        with open(f"natija_{_HOLAT['id']}.json", 'w', encoding='utf-8') as f:
            json.dump({'id': _HOLAT['id'], 'variant': _HOLAT['v'] + 1, 'ball': jami,
                       'maks': maks, 'topshiriqlar': _HOLAT['natija']}, f, ensure_ascii=False)
    return jami
