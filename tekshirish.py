# Javobni bir xil ko'rinishga keltirish (xeshlash uchun)
# ----------------------------------------------------------------------
def _son(x):
    return f"{float(x):.2f}"

def _norm(tur, javob):
    if tur == 'son':
        return _son(javob)
    if tur == 'matn':
        return str(javob).strip()
    if tur == 'butun':
        return str(int(round(float(javob))))
    if tur == 'royxat':                      # tartib muhim
        return '|'.join(_son(x) if isinstance(x, (int, float, np.number)) else str(x).strip()
                        for x in list(javob))
    if tur == 'toplam':                      # tartib muhim emas
        return '|'.join(sorted(str(x).strip() for x in list(javob)))
    if tur == 'lugat':                       # dict yoki Series: kalit -> son
        items = dict(javob).items() if not isinstance(javob, pd.Series) else javob.items()
        return '|'.join(f"{str(k).strip()}={_son(v)}" for k, v in sorted(items, key=lambda kv: str(kv[0])))
    if tur == 'jadval':                      # DataFrame: indeks, ustunlar, qiymatlar
        df = javob.copy()
        df.index = [str(i) for i in df.index]
        df.columns = [str(c) for c in df.columns]
        df = df.sort_index().reindex(sorted(df.columns), axis=1)
        df = df.apply(pd.to_numeric, errors='coerce').fillna(0)   # NaN va 0 bir xil hisoblanadi
        df = df.loc[(df != 0).any(axis=1)]                        # butunlay 0 bo'lgan qatorlar tashlanadi
        qiymat = '|'.join(_son(x) if pd.notna(x) else 'nan' for x in df.to_numpy().ravel())
        return ','.join(df.index) + '#' + ','.join(df.columns) + '#' + qiymat
    if tur == 'shakl':
        return str(tuple(int(x) for x in javob))
    raise ValueError(tur)

def _xesh(kalit, v, matn):
    return hashlib.sha256(f"{_TUZ}|{kalit}|{v}|{matn}".encode()).hexdigest()[:16]


